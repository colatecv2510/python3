payaso = int(input("Introduce el número de payasos que lleva el pedido: "))
muñeca = int(input("Introduce el número de muñecas que lleva el pedido: "))
pesopayaso = 112
pesomuñeca = 75
pedido = ((payaso*pesopayaso) + (muñeca*pesomuñeca))
